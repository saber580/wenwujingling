  /* ================= 核心动作 ================= */
  function vnOpen(id) {
    const n = vnNode(id);
    if (!n || String(id).endsWith("_ev")) return;
    /* 隐藏结局：条件没到，流程图上的这张卡就是锁着的——不解锁、不解密 */
    if (n.locked && !vnChoiceOpen({ need: n.locked })) {
      vnTip("这一页还空着。等你真的跟它们说过话，它自己会亮。");
      return;
    }
    /* 首次进开场：先问家乡（玩家不是透明人） */
    if (id === "open" && !VN.player.hometown && !VN.playerAsked) {
      VN.playerAsked = true;
      VN.current = "player";
      VN.view = "node";
      VN.nodeLines = VN_PLAYER_NODE.lines.slice();
      VN.nodeCursor = 1;
      vnSave(); vnPaint();
      return;
    }
    VN.current = id;
    VN.lastNode = id;
    VN.cam = null;
    VN.sideMode = null;
    if (n.ending) { VN.endings[n.ending] = true; vnSave(); }
    if (!VN.path.includes(id)) VN.path.push(id);
    VN.view = "node";
    VN.nodeLines = n.lines.slice();
    /* 支线做完再结缘，会多一句回响 */
    if (n.kind === "win" && n.echo && VN.quests[n.station]) VN.nodeLines = VN.nodeLines.concat(n.echo);
    /* 走到家乡站：家门口的质问（让「青年对家乡文物失联」真正砸在玩家身上） */
    if (n.kind === "hub" && VN.player.hometown === n.station) {
      VN.nodeLines = VN.nodeLines.concat(vnHometownLines(n.station));
    }
    VN.nodeCursor = 1;
    vnSave(); vnPaint();
  }

